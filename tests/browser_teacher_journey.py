#!/usr/bin/env python3
"""Professor: autoria, critérios, módulo, catalogação e começo da investigação."""
from pathlib import Path
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parent.parent
html=(root/'standalone.html').read_text('utf-8')
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 for w,h in ((1440,900),(390,844)):
  ctx=browser.new_context(viewport={'width':w,'height':h},is_mobile=w<=900,has_touch=w<=900)
  pg=ctx.new_page();errors=[];pg.on('pageerror',lambda e:errors.append(str(e)))
  pg.evaluate('''() => {const d=new Map();Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>d.get(k)??null,setItem:(k,v)=>d.set(k,String(v)),removeItem:k=>d.delete(k)}})}''')
  pg.set_content(html,wait_until='domcontentloaded')
  pg.evaluate('location.hash="#/professor"');pg.wait_for_timeout(90)
  pg.locator('#edu-form-kind').select_option('script')
  pg.locator('#edu-form-module').select_option('medir')
  pg.locator('#edu-form-title').fill('Investigação personalizada de instrumentos')
  pg.locator('#edu-form-description').fill('Observar, medir e confirmar uma investigação genérica.')
  pg.locator('[data-teacher-next="2"]').click()
  assert pg.locator('[data-teacher-panel="2"]').is_visible()
  pg.locator('#edu-step-one-label').fill('Selecionar o objeto inicial')
  pg.locator('#edu-step-one-rule').select_option('selection')
  pg.locator('#edu-step-two-label').fill('Registrar uma leitura')
  pg.locator('#edu-step-two-rule').select_option('readings')
  pg.locator('#edu-add-step').click()
  assert pg.locator('#edu-extra-steps fieldset').count()==1
  pg.locator('#edu-step-three-label').fill('Conferir o procedimento')
  pg.locator('[data-teacher-next="3"]').click()
  assert pg.locator('[data-teacher-panel="3"]').is_visible(),(w,'wizard')
  assert 'Módulo: Medir' in pg.locator('#edu-teacher-preview').inner_text()
  assert '3. Conferir o procedimento' in pg.locator('#edu-teacher-preview').inner_text()
  pg.locator('#edu-teacher-form button[type="submit"]').click()
  pg.wait_for_timeout(110)
  assert pg.locator('#edu-teacher-list .edu-teacher-item').count()==1,(w,pg.locator('#edu-teacher-summary').inner_text())
  pg.evaluate('location.hash="#/roteiros"');pg.wait_for_timeout(100)
  custom=pg.locator('#edu-script-list .edu-card').filter(has_text='Investigação personalizada de instrumentos')
  assert custom.count()==1,(w,'catalog')
  custom.locator('button').click();pg.wait_for_timeout(70)
  assert 'Medir' in pg.locator('#edu-script-detail .edu-kicker').inner_text()
  pg.locator('#edu-script-detail button:has-text("Montar na bancada")').click()
  pg.wait_for_timeout(100)
  assert pg.evaluate('BaseDemoSI.currentModule()')=='medir',(w,'assigned module')
  assert pg.locator('.scene-entity').count()==1,(w,'prepared observation object')
  assert pg.locator('[data-left-tab="preparo"]').evaluate('(el)=>el.hidden'),(w,'measure forbids tool addition')
  pg.evaluate('location.hash="#/roteiros"');pg.wait_for_timeout(100)
  pg.locator('#edu-script-list .edu-card').filter(has_text='Investigação personalizada de instrumentos').locator('button').click();pg.wait_for_timeout(90)
  pg.locator('#edu-script-detail button:has-text("Encerrar atividade")').click()
  pg.locator('#si-modal-confirm').click();pg.wait_for_timeout(90)
  assert pg.evaluate('BaseDemoSI.currentModule()')=='livre',(w,'original module')
  assert not errors,(w,errors)
  print(f'OK: {w} px — professor, 3 etapas, modo Medir, catálogo, início, módulo restaurado')
  ctx.close()
 browser.close()
