#!/usr/bin/env python3
"""Interrupção/retomada: identificação, relatório parcial/final e estado livre."""
from pathlib import Path
from playwright.sync_api import sync_playwright
html=(Path(__file__).resolve().parent.parent/'standalone.html').read_text('utf8')
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 for width,height in [(1440,900),(390,844)]:
  context=browser.new_context(viewport={'width':width,'height':height},is_mobile=width<700,has_touch=width<700)
  page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.evaluate("""() => {const d=new Map();Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>d.get(k)??null,setItem:(k,v)=>d.set(k,String(v))}})}""")
  page.set_content(html,wait_until='domcontentloaded')
  page.evaluate('location.hash="#/missoes?item=mission-create"');page.wait_for_timeout(90)
  detail=page.locator('#edu-mission-detail')
  detail.locator('input[name=nome]').fill('Nome persistente')
  detail.locator('input[name=turma]').fill('Turma C')
  detail.locator('button:has-text("Montar na bancada")').click();page.wait_for_timeout(85)
  page.locator('[data-open-dock="montagem"]').click();page.locator('[data-left-tab="preparo"]').click()
  page.locator('[data-add-kind="block"]').click();page.locator('[data-close-dock="left"]').click()
  page.evaluate('location.hash="#/missoes?item=mission-create"');page.wait_for_timeout(75)
  detail.locator('button:has-text("Encerrar atividade")').click();page.locator('#si-modal-confirm').click();page.wait_for_timeout(70)
  page.evaluate('location.hash="#/relatorios"');page.wait_for_timeout(70)
  assert page.locator('#reports-entries .si-report-entry').count()==1,(width,'partial snapshot')
  assert '0/1' in page.locator('#report-preview').inner_text(),(width,'partial status')
  page.evaluate('location.hash="#/missoes?item=mission-create"');page.wait_for_timeout(70)
  assert detail.locator('input[name=nome]').input_value()=='Nome persistente',(width,'checkpoint identity')
  assert detail.locator('input[name=turma]').input_value()=='Turma C',(width,'checkpoint class')
  detail.locator('button:has-text("Montar na bancada")').click();page.wait_for_timeout(70)
  assert page.locator('.scene-entity').count()==1,(width,'checkpoint scene')
  page.locator('[data-open-dock="montagem"]').click();page.locator('[data-left-tab="preparo"]').click()
  page.locator('[data-add-kind="circle"]').click();page.locator('[data-close-dock="left"]').click()
  page.evaluate('location.hash="#/missoes?item=mission-create"');page.wait_for_timeout(70)
  detail.locator('button:has-text("Conferir e registrar")').click();page.wait_for_timeout(80)
  detail.locator('button:has-text("Encerrar atividade")').click();page.locator('#si-modal-confirm').click();page.wait_for_timeout(80)
  page.evaluate('location.hash="#/relatorios"');page.wait_for_timeout(65)
  assert page.locator('#reports-entries .si-report-entry').count()==2,(width,'final snapshot follows partial')
  report=page.locator('#report-preview').inner_text()
  assert '1/1' in report and 'Nome persistente' in report and 'Turma C' in report,(width,report[:350])
  assert not errors,(width,errors)
  print('OK',width,'px: interrupção, identidade e bancada recuperadas, relatórios parcial e final separados')
  context.close()
 browser.close()
